import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {build} from 'esbuild';

const root=process.cwd(),dir=fs.mkdtempSync(path.join(root,'.test-friendly-organizer-'));
const bundle=path.join(dir,'friendlies.mjs'),competitionBundle=path.join(dir,'competition.mjs'),ratingBundle=path.join(dir,'rating.mjs');
process.env.MATCHROOM_DATA_DIR=dir;
let testDb;
try{
  await build({entryPoints:['lib/friendlies-server.ts'],bundle:true,platform:'node',format:'esm',packages:'external',outfile:bundle});
  await build({entryPoints:['lib/competition-server.ts'],bundle:true,platform:'node',format:'esm',packages:'external',outfile:competitionBundle});
  await build({entryPoints:['lib/competition.ts'],bundle:true,platform:'node',format:'esm',packages:'external',outfile:ratingBundle});
  const {database}=await import('../scripts/local-store.mjs');
  const {friendlyAction,getFriendlies}=await import(pathToFileURL(bundle).href);
  const {communityRankings}=await import(pathToFileURL(competitionBundle).href);
  const {eloRankings}=await import(pathToFileURL(ratingBundle).href);
  const rating=(homeGoals,awayGoals)=>eloRankings([{id:'h',name:'Home',created_at:'now'},{id:'a',name:'Away',created_at:'now'}],[{id:'one',home:'h',away:'a',homeGoals,awayGoals,score:homeGoals>awayGoals?1:homeGoals<awayGoals?0:0.5,at:'2026-01-01',order:1}]).find(p=>p.id==='h').lastChange;
  assert.ok(rating(4,0)>rating(2,0));
  assert.ok(rating(2,0)>rating(2,1));
  assert.equal(rating(0,0),0);
  const db=testDb=database();
  const profile=name=>JSON.stringify({displayName:name,teams:[{kind:'football',name:'Arsenal'}],primary:null,platforms:['PC'],timezone:'UTC',psnId:'',eaId:name+'_ea'});
  for(const [id,owner] of [['owner',1],['a',0],['b',0],['c',0]]){
    db.prepare('INSERT INTO accounts(id,email,name,password_hash,owner,created_at) VALUES(?,?,?,?,?,?)').run(id,'',id,'hash',owner,'now');
    db.prepare('INSERT INTO account_usernames(username,account_id,created_at) VALUES(?,?,?)').run(id+'_user',id,'now');
    db.prepare('INSERT INTO account_profiles(account_id,data,updated_at) VALUES(?,?,?)').run(id,profile(id),'now');
  }
  const config={tournamentId:'t',name:'Test',pots:[{id:'p',name:'P'}],managers:[{id:'ma',name:'A'},{id:'mb',name:'B'}],clubs:[{id:'ca',name:'A',pot:'p'},{id:'cb',name:'B',pot:'p'}]};
  db.prepare('INSERT INTO tournaments(id,name,owner_id,config,created_at) VALUES(?,?,?,?,?)').run('t','Test','owner',JSON.stringify(config),'now');
  for(const id of ['a','b','c']){
    db.prepare('INSERT INTO community_players(id,owner_id,name,created_at) VALUES(?,?,?,?)').run('p-'+id,'owner',id,'now');
    db.prepare('UPDATE account_usernames SET player_id=? WHERE account_id=?').run('p-'+id,id);
    db.prepare("INSERT INTO members(id,tournament_id,user_id,email,name,role,player_id,username) VALUES(?,'t',?,'',?,'manager',?,?)")
      .run('m-'+id,id,id,'p-'+id,id+'_user');
  }
  const actor=id=>({userId:id,displayName:id});
  const local=new Date(Date.now()+3*86400000).toISOString().slice(0,16);
  assert.throws(()=>friendlyAction(actor('a'),{action:'organize',firstId:'a',secondId:'b',local}),/Only the organizer/);
  const {id}=friendlyAction(actor('owner'),{action:'organize',firstId:'a',secondId:'b',local,message:'Club friendly'});
  assert.ok(id);
  assert.equal(getFriendlies(actor('c')).invitations.length,0);
  assert.equal(getFriendlies(actor('owner')).invitations[0].organizerView,true);
  assert.equal(getFriendlies(actor('a')).invitations[0].myTurn,true);
  assert.equal(getFriendlies(actor('b')).invitations[0].myTurn,false);
  friendlyAction(actor('a'),{action:'accept',id,version:1});
  assert.equal(getFriendlies(actor('a')).invitations[0].status,'pending');
  assert.equal(getFriendlies(actor('b')).invitations[0].myTurn,true);
  assert.equal(getFriendlies(actor('owner')).invitations[0].firstResponse,true);
  friendlyAction(actor('b'),{action:'accept',id,version:2});
  assert.equal(getFriendlies(actor('owner')).invitations[0].status,'accepted');
  const secondLocal=new Date(Date.now()+5*86400000).toISOString().slice(0,16);
  const counterLocal=new Date(Date.now()+6*86400000).toISOString().slice(0,16);
  const counterId=friendlyAction(actor('owner'),{action:'organize',firstId:'a',secondId:'b',local:secondLocal}).id;
  friendlyAction(actor('a'),{action:'counter',id:counterId,version:1,local:counterLocal});
  assert.equal(getFriendlies(actor('b')).invitations.find(i=>i.id===counterId).myTurn,true);
  friendlyAction(actor('b'),{action:'accept',id:counterId,version:2});
  assert.equal(getFriendlies(actor('owner')).invitations.find(i=>i.id===counterId).status,'accepted');
  const cancelLocal=new Date(Date.now()+8*86400000).toISOString().slice(0,16);
  const cancelId=friendlyAction(actor('owner'),{action:'organize',firstId:'a',secondId:'c',local:cancelLocal}).id;
  friendlyAction(actor('owner'),{action:'cancel',id:cancelId,version:1});
  assert.equal(getFriendlies(actor('c')).invitations.find(i=>i.id===cancelId).status,'cancelled');
  db.prepare('UPDATE friendly_elo_start SET started_at=? WHERE id=1').run(new Date(Date.now()-3*86400000).toISOString());
  const playedLocal=new Date(Date.now()-86400000).toISOString().slice(0,16);
  const playedId=friendlyAction(actor('owner'),{action:'log',asPlayerId:'a',opponentId:'b',local:playedLocal,myGoals:2,theirGoals:1,myStars:4,theirStars:3.5}).id;
  assert.equal(getFriendlies(actor('owner')).invitations.find(i=>i.id===playedId).elo?.state,'counts');
  assert.equal(getFriendlies(actor('c')).invitations.some(i=>i.id===playedId),false);
  assert.throws(()=>friendlyAction(actor('a'),{action:'cancel',id:playedId,version:1,message:'Incorrect game'}),/Only the organizer/);
  assert.throws(()=>friendlyAction(actor('owner'),{action:'cancel',id:playedId,version:1,message:'No'}),/reason of at least 3/);
  friendlyAction(actor('owner'),{action:'cancel',id:playedId,version:1,message:'Duplicate match'});
  const voided=getFriendlies(actor('owner')).invitations.find(i=>i.id===playedId);
  assert.equal(voided.status,'cancelled');
  assert.equal(voided.elo,null);
  assert.ok(voided.result);
  assert.equal(getFriendlies(actor('a')).invitations.find(i=>i.id===playedId).status,'cancelled');
  assert.throws(()=>friendlyAction(actor('owner'),{action:'cancel',id:playedId,version:2,message:'Again'}),/already closed/);
  const otherPlayed=friendlyAction(actor('a'),{action:'log',opponentId:'c',local:playedLocal,myGoals:0,theirGoals:0,myStars:null,theirStars:null}).id;
  assert.ok(getFriendlies(actor('owner')).invitations.some(i=>i.id===otherPlayed));
  friendlyAction(actor('owner'),{action:'cancel',id:otherPlayed,version:1,message:'Entered by mistake'});
  assert.equal(getFriendlies(actor('c')).invitations.find(i=>i.id===otherPlayed).status,'cancelled');
  const correctedLocal=new Date(Date.now()-2*86400000).toISOString().slice(0,16);
  const editId=friendlyAction(actor('owner'),{action:'log',asPlayerId:'a',opponentId:'c',local:correctedLocal,myGoals:1,theirGoals:0,myStars:3.5,theirStars:4}).id;
  const editTime=new Date(Date.now()-2*86400000+60000).toISOString().slice(0,16);
  const correction={action:'admin-result',id:editId,version:1,local:editTime,firstGoals:2,secondGoals:3,firstStars:4.5,secondStars:5,reason:'Corrected from match notes'};
  assert.throws(()=>friendlyAction(actor('b'),correction),/Invitation not found/);
  friendlyAction(actor('owner'),correction);
  const edited=getFriendlies(actor('owner')).invitations.find(i=>i.id===editId);
  assert.equal(edited.version,2);
  assert.equal(edited.result.first.goals,2);
  assert.equal(edited.result.second.goals,3);
  assert.equal(edited.result.second.stars,5);
  assert.equal(edited.elo.state,'counts');
  assert.ok(getFriendlies(actor('owner')).events.some(e=>e.invitationId===editId&&e.action==='corrected'&&e.reason==='Corrected from match notes'));
  assert.throws(()=>friendlyAction(actor('owner'),correction),/changed/);
  const ultimateLocal=new Date(Date.now()-3*86400000+60000).toISOString().slice(0,16);
  assert.throws(()=>friendlyAction(actor('owner'),{action:'log',mode:'clubs',asPlayerId:'b',opponentId:'c',local:ultimateLocal,myGoals:2,theirGoals:0,myStars:3,theirStars:4}),/at least 3.5/);
  const ultimateId=friendlyAction(actor('owner'),{action:'log',mode:'ultimate',asPlayerId:'b',opponentId:'c',local:ultimateLocal,myGoals:2,theirGoals:0,myStars:null,theirStars:null}).id;
  assert.equal(getFriendlies(actor('owner')).invitations.find(i=>i.id===ultimateId).mode,'ultimate');
  assert.equal(getFriendlies(actor('owner')).invitations.find(i=>i.id===ultimateId).elo.state,'counts');
  assert.throws(()=>friendlyAction(actor('owner'),{action:'log',opponentId:'a',local:playedLocal,myGoals:2,theirGoals:1,myStars:null,theirStars:null}),/linked Elo player/);
  const legacyId='legacy-admin-log';
  db.prepare("INSERT INTO friendly_invitations(id,inviter_id,invitee_id,pair_key,status,proposed_at,proposed_local,proposer_timezone,proposed_by,turn_id,created_at,updated_at) VALUES(?,'owner','a','a|owner','accepted',?,?,'UTC','owner',NULL,?,?)")
    .run(legacyId,new Date(playedLocal+'Z').toISOString(),playedLocal,'now','now');
  db.prepare("INSERT INTO friendly_events(id,invitation_id,actor_id,actor_name,at,action,reason,proposed_at) VALUES(?,?,?,?,?,?,?,?)")
    .run('legacy-log',legacyId,'owner','owner',new Date().toISOString(),'logged',null,new Date(playedLocal+'Z').toISOString());
  db.prepare("INSERT INTO friendly_events(id,invitation_id,actor_id,actor_name,at,action,reason,proposed_at) VALUES(?,?,?,?,?,?,?,?)")
    .run('legacy-score',legacyId,'owner','owner',new Date().toISOString(),'result',JSON.stringify({inviter:{goals:3,stars:null},invitee:{goals:1,stars:null}}),new Date(playedLocal+'Z').toISOString());
  assert.match(getFriendlies(actor('owner')).invitations.find(i=>i.id===legacyId).ratingIssue,/no linked player profile/);
  const beforeRated=communityRankings('owner').find(p=>p.id==='p-b').played;
  friendlyAction(actor('owner'),{action:'reassign',id:legacyId,version:1,firstId:'b',secondId:'a',reason:'Admin login was used'});
  const corrected=getFriendlies(actor('owner')).invitations.find(i=>i.id===legacyId);
  assert.equal(corrected.ratingIssue,null);
  assert.equal(corrected.elo.state,'counts');
  assert.equal(corrected.result.mine.goals,3);
  assert.equal(communityRankings('owner').find(p=>p.id==='p-b').played,beforeRated+1);
  assert.equal(getFriendlies(actor('b')).invitations.find(i=>i.id===legacyId).status,'accepted');
  assert.equal(getFriendlies(actor('c')).invitations.some(i=>i.id===legacyId),false);
  db.prepare('INSERT INTO accounts(id,email,name,password_hash,owner,created_at) VALUES(?,?,?,?,?,?)').run('xavier','','Xavier','hash',0,'now');
  db.prepare('INSERT INTO account_usernames(username,account_id,created_at) VALUES(?,?,?)').run('xavier_user','xavier','now');
  db.prepare('INSERT INTO account_profiles(account_id,data,updated_at) VALUES(?,?,?)').run('xavier',JSON.stringify({displayName:'Xavier',teams:[],primary:null,platforms:[],timezone:'',psnId:'',eaId:''}),'now');
  db.prepare("INSERT INTO members(id,tournament_id,user_id,email,name,role,username) VALUES(?,'t',?,'',?,'manager',?)").run('m-xavier','xavier','Xavier','xavier_user');
  db.prepare('INSERT INTO community_players(id,owner_id,name,created_at) VALUES(?,?,?,?)').run('p-xavier','owner','Xavier','now');
  const xavierEntry=getFriendlies(actor('owner')).directory.find(p=>p.id==='xavier');
  assert.equal(xavierEntry.name,'Xavier');
  assert.equal(xavierEntry.ranked,false);
  assert.equal(xavierEntry.eligible,false);
  assert.throws(()=>friendlyAction(actor('a'),{action:'link-player',accountId:'xavier',playerId:'p-xavier'}),/Only the organizer/);
  friendlyAction(actor('owner'),{action:'link-player',accountId:'xavier',playerId:'p-xavier'});
  assert.equal(getFriendlies(actor('owner')).directory.find(p=>p.id==='xavier').ranked,true);
  const xavierGame=friendlyAction(actor('owner'),{action:'log',asPlayerId:'b',opponentId:'xavier',local:playedLocal,myGoals:1,theirGoals:2,myStars:null,theirStars:null}).id;
  assert.equal(getFriendlies(actor('owner')).invitations.find(i=>i.id===xavierGame).elo.state,'counts');
  assert.equal(communityRankings('owner').find(p=>p.id==='p-xavier').played,1);
  assert.deepEqual(db.prepare('PRAGMA foreign_key_check').all(),[]);
  console.log('PASS: Xavier appears in the admin picker, can be linked to an Elo profile, and his logged match is rated.');
}finally{
  try{testDb?.close();}catch{/* already closed */}
  if(!dir.startsWith(root+path.sep))throw new Error('Test directory escaped the H: project.');
  fs.rmSync(dir,{recursive:true,force:true});
}
